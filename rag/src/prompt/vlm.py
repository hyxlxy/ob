# 场景关键词匹配（用于自动选择提示词）
SCENE_KEYWORDS = {
    "financial": ["盈利预测", "财务预测", "利润表", "资产负债", "现金流", "EPS", "ROE", "PE", "估值"],
    "product": ["产品", "品类", "油条", "蒸煎饺", "蛋挞", "油炸", "烘焙", "蒸煮", "菜肴", "SKU"],
    "channel": ["渠道", "客户", "经销商", "直营", "大B", "小B", "百胜", "华莱士", "区域"],
    "capacity": ["产能", "产量", "工厂", "供应链", "原材料", "成本", "产销率", "外协"],
    "industry": ["行业", "市场规模", "竞争", "市占率", "速冻食品", "预制菜", "CAGR", "连锁化"],
    "strategy": ["战略", "风险", "股权激励", "御知菜", "C端", "募投", "扩张"],
}


def select_prompt_by_content(text_hint: str = "") -> str:
    """
    根据页面文本内容自动选择最匹配的提示词。
    
    Args:
        text_hint: 页面的部分文本内容（用于判断场景）
        
    Returns:
        最匹配的提示词字符串
    """
    if not text_hint:
        return VLM_IMAGE_EXTRACTION_PROMPT
    
    # 统计各场景关键词匹配数
    scene_scores = {}
    for scene, keywords in SCENE_KEYWORDS.items():
        score = sum(1 for kw in keywords if kw in text_hint)
        if score > 0:
            scene_scores[scene] = score
    
    # 如果有匹配，返回得分最高的场景提示词
    if scene_scores:
        best_scene = max(scene_scores, key=scene_scores.get)
        return SCENE_PROMPTS[best_scene]
    
    # 默认返回通用提示词
    return VLM_IMAGE_EXTRACTION_PROMPT
